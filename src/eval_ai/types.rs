//! Core data models for GenAI and Agent evaluation.

use std::path::PathBuf;

use clap::Args;
use serde::{Deserialize, Serialize};

#[derive(Args, Debug, Clone, Default, Serialize, Deserialize)]
pub struct EvalAiOpts {
    /// Input dataset path (JSON array or JSONL file with query, context, response, expected)
    #[arg(long)]
    pub dataset: Option<PathBuf>,
    /// Single query / user prompt to evaluate
    #[arg(long)]
    pub query: Option<String>,
    /// Retrieved context documents / passages to evaluate against
    #[arg(long)]
    pub context: Option<String>,
    /// Actual response generated by target LLM / RAG app
    #[arg(long)]
    pub response: Option<String>,
    /// Ground truth expected answer (optional)
    #[arg(long)]
    pub expected: Option<String>,
    /// Agent trajectory trace file (JSON array of steps/tool calls)
    #[arg(long)]
    pub trajectory: Option<PathBuf>,
    /// Output format: table, json, markdown
    #[arg(long, default_value = "table")]
    pub format: String,
    /// Quality pass threshold (0.0 to 1.0)
    #[arg(long, default_value_t = 0.70)]
    pub threshold: f64,
    /// Save full evaluation report to file
    #[arg(long)]
    pub out: Option<PathBuf>,
    /// Run adversarial safety checks (prompt injection, token leaks, canaries)
    #[arg(long)]
    pub red_team: bool,
}

/// Lexical-heuristic RAG triad. Every score is `None` when it could not be measured — an
/// unmeasured metric is reported as such and never as a perfect 1.0. See `method` for what the
/// numbers actually are: stopword-filtered token overlap, not an embedding-based metric.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RagTriadScore {
    pub context_relevance: Option<f64>,
    pub faithfulness: Option<f64>,
    pub answer_relevance: Option<f64>,
    /// Weighted mean of the metrics that were measured; `None` when none were.
    pub composite_score: Option<f64>,
    pub hallucination_count: usize,
    pub hallucinations: Vec<HallucinationDetail>,
    /// Metric names rendered as `null` in this result (no context, empty answer, …).
    #[serde(default)]
    pub not_evaluated: Vec<String>,
    /// How the numeric scores were computed, so the label cannot be mistaken for a semantic metric.
    pub method: String,
}

impl RagTriadScore {
    pub fn not_evaluated(&self, metric: &str) -> bool {
        self.not_evaluated.iter().any(|m| m == metric)
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct HallucinationDetail {
    pub claim: String,
    pub reason: String,
    pub ungrounded_terms: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TrajectoryEval {
    pub total_steps: usize,
    pub redundant_steps: usize,
    pub schema_violations: usize,
    pub loop_detected: bool,
    pub efficiency_score: f64,
    pub issues: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RedTeamCheck {
    pub prompt_injection_detected: bool,
    pub sensitive_data_leak: bool,
    pub canary_leak: bool,
    pub safety_score: f64,
    pub findings: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AiTestCase {
    pub id: String,
    pub query: String,
    #[serde(default)]
    pub context: Option<String>,
    pub response: String,
    #[serde(default)]
    pub expected: Option<String>,
    #[serde(default)]
    pub trajectory: Option<Vec<serde_json::Value>>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AiTestResult {
    pub case_id: String,
    pub passed: bool,
    pub rag_triad: Option<RagTriadScore>,
    pub trajectory_eval: Option<TrajectoryEval>,
    pub red_team: Option<RedTeamCheck>,
    /// `None` when no metric could be measured for this case — not a zero score.
    pub overall_score: Option<f64>,
    pub feedback: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AiEvalReport {
    pub timestamp: String,
    pub total_cases: usize,
    pub passed_cases: usize,
    pub failed_cases: usize,
    pub pass_rate: f64,
    /// Mean over the cases that were measured; `None` when none were.
    pub avg_rag_score: Option<f64>,
    /// Mean over the cases whose faithfulness was measurable; `None` when none were.
    pub avg_faithfulness: Option<f64>,
    pub results: Vec<AiTestResult>,
}
