//! Universal GenAI & Agent Evaluator (readyhai eval-ai).
//! Evaluates RAG pipelines, LLM outputs, and AI agent trajectories:
//! 1. RAG Quality Triad: Context Relevance, Groundedness / Faithfulness (Hallucination detection), Answer Relevance.
//! 2. Agent Trajectory & Tool-Calling Validation: Schema conformance, cyclic loop detection, efficiency scoring.
//! 3. Adversarial Red-Teaming: Indirect prompt injection detection, system prompt extraction, sensitive data leakage.
//! 4. 100% Offline & Deterministic: runs mathematical heuristics without requiring external cloud LLMs.

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};
use std::collections::HashSet;
use std::fs;
use std::path::PathBuf;
use std::time::Instant;

#[derive(clap::Args, Debug, Clone, Default, Serialize, Deserialize)]
pub struct EvalAiOpts {
    /// Input dataset path (JSON array or JSONL file with query, context, response, expected)
    #[arg(long)]
    pub dataset: Option<PathBuf>,
    /// Single query / user prompt to evaluate
    #[arg(long)]
    pub query: Option<String>,
    /// Retrieved context documents / passages to evaluate against
    #[arg(long)]
    pub context: Option<String>,
    /// Actual response generated by target LLM / RAG app
    #[arg(long)]
    pub response: Option<String>,
    /// Ground truth expected answer (optional)
    #[arg(long)]
    pub expected: Option<String>,
    /// Agent trajectory trace file (JSON array of steps/tool calls)
    #[arg(long)]
    pub trajectory: Option<PathBuf>,
    /// Output format: table, json, markdown
    #[arg(long, default_value = "table")]
    pub format: String,
    /// Quality pass threshold (0.0 to 1.0)
    #[arg(long, default_value_t = 0.70)]
    pub threshold: f64,
    /// Save full evaluation report to file
    #[arg(long)]
    pub out: Option<PathBuf>,
    /// Run adversarial safety checks (prompt injection, token leaks, canaries)
    #[arg(long)]
    pub red_team: bool,
}

// ------------------------------------------------------------------ data models

