//! Pull Request markdown authoring from remediation reports, stating per patch whether a test
//! suite actually ran against it.

use super::types::{FixReport, PatchStatus};

/// Author complete Pull Request markdown description.
pub fn generate_pr_markdown(report: &FixReport) -> String {
    let mut md = String::new();
    md.push_str(&format!(
        "# 🛡️ ReadyHai Remediation: {}\n\n",
        report.pr_title
    ));
    md.push_str(
        "> 🤖 **Automated Quality Patch** synthesized by ReadyHai Agentic Fixer. Verification \
         status is reported per patch below — a passing repository test suite means that suite \
         still passes, not that regressions are impossible.\n\n",
    );

    md.push_str("### 📋 Executive Summary\n");
    md.push_str("| Metric | Value |\n|---|---|\n");
    md.push_str(&format!("| **Target Repository** | `{}` |\n", report.repo));
    md.push_str(&format!(
        "| **Test-Suite Verified Patches** | `{}` |\n",
        report.patches_verified
    ));
    md.push_str(&format!(
        "| **Patches Without Verification** | `{}` |\n",
        report.patches_unverified
    ));
    md.push_str(&format!(
        "| **Patches Applied** | `{}` |\n",
        report.patches_applied
    ));
    if let Some(branch) = &report.branch_created {
        md.push_str(&format!("| **Git Branch** | `{branch}` |\n"));
    }
    if let Some(sha) = &report.commit_sha {
        md.push_str(&format!("| **Commit SHA** | `{sha}` |\n"));
    }
    md.push_str("\n---\n\n");

    md.push_str("### 🛠️ Synthesized Patches & Verification\n\n");
    for (idx, p) in report.patches.iter().enumerate() {
        let status_emoji = match p.status {
            PatchStatus::Verified | PatchStatus::Applied => "✅",
            PatchStatus::AppliedWithoutVerification => "⚠️",
            PatchStatus::Synthesized => "🔍",
            PatchStatus::VerificationFailed => "❌",
            PatchStatus::RolledBack => "↩️",
        };

        md.push_str(&format!(
            "#### {} Patch #{}: `{}` ({})\n",
            status_emoji,
            idx + 1,
            p.file_path,
            p.rule
        ));
        md.push_str(&format!("- **Location:** `{}:{}`\n", p.file_path, p.line));
        md.push_str(&format!("- **Remediation Rationale:** {}\n", p.rationale));
        match p.status {
            PatchStatus::Verified | PatchStatus::Applied => {
                let runner = p.verification_runner.as_deref().unwrap_or("test suite");
                let dur = p.verification_duration_ms.unwrap_or(0);
                md.push_str(&format!(
                    "- **Local test suite:** `{runner}` passed in {dur}ms with this patch applied \
                     (covers only what the suite itself tests)\n"
                ));
            }
            PatchStatus::AppliedWithoutVerification => md.push_str(
                "- **Local test suite:** not run — no supported runner was detected, or \
                 `--verify` was off. This patch was **not** checked.\n",
            ),
            PatchStatus::VerificationFailed => {
                md.push_str("- **Local test suite:** failed with this patch applied.\n");
            }
            _ => md.push_str("- **Local test suite:** not run.\n"),
        }
        md.push_str("\n<details>\n<summary><b>View Unified Code Diff</b></summary>\n\n```diff\n");
        md.push_str(&p.unified_diff);
        md.push_str("\n```\n</details>\n\n");
    }

    md.push_str("### 🧪 Evidence Ledger & Verification\n");
    md.push_str(
        "Patches are synthesized from AST analysis of the patched file. A patch is marked verified \
         only when the repository's own test suite ran with it applied and passed; patches with no \
         detected runner, or when verification was disabled, are listed as unverified above. Under \
         ReadyHai's safe Push Policy, remote commits are never pushed automatically.\n\n",
    );
    md.push_str("```bash\n# Verify patched suite locally\nreadyhai fix --repo . --verify\n```\n\n");
    md.push_str("*Autogenerated by [ReadyHai](https://github.com/deziss/readyhai) · Autonomous QA & Remediation Engine.*");

    md
}
